"""Persistence for graph analyses in SQLite locally and PostgreSQL on Render."""

import json
import os
from pathlib import Path
import sqlite3
from contextlib import contextmanager


class AnalysisStorageError(Exception):
    """Raised when a database operation fails."""


class AnalysisRepository:
    """Stores analyses and returns the most recent saved graphs."""

    def __init__(self, database_url):
        self.database_url = database_url
        self.is_postgres = database_url.startswith(("postgres://", "postgresql://"))
        if self.is_postgres:
            self._initialize_postgres()
        else:
            self.database_path = Path(database_url)
            self.database_path.parent.mkdir(parents=True, exist_ok=True)
            self._initialize_sqlite()

    @classmethod
    def from_environment(cls):
        database_url = os.environ.get("DATABASE_URL")
        if database_url:
            return cls(database_url)
        default_path = Path(__file__).resolve().parents[2] / ".data" / "analyses.sqlite3"
        return cls(os.environ.get("ANALYSIS_DB_PATH", str(default_path)))

    def _connect_postgres(self):
        import psycopg

        url = self.database_url.replace("postgres://", "postgresql://", 1)
        return psycopg.connect(url, connect_timeout=10)

    def _initialize_postgres(self):
        with self._connect_postgres() as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS graph_analyses (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    vertices JSONB NOT NULL,
                    edges JSONB NOT NULL,
                    result JSONB NOT NULL
                )
                """
            )

    def _connect_sqlite(self):
        connection = sqlite3.connect(self.database_path, timeout=10)
        connection.row_factory = sqlite3.Row
        return connection

    @contextmanager
    def _sqlite_session(self):
        connection = self._connect_sqlite()
        try:
            with connection:
                yield connection
        finally:
            connection.close()

    def _initialize_sqlite(self):
        with self._sqlite_session() as connection:
            connection.execute(
                """
                CREATE TABLE IF NOT EXISTS graph_analyses (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    created_at TEXT NOT NULL DEFAULT (
                        strftime('%Y-%m-%dT%H:%M:%fZ', 'now')
                    ),
                    vertices TEXT NOT NULL,
                    edges TEXT NOT NULL,
                    result TEXT NOT NULL
                )
                """
            )

    def save(self, vertices, edges, result):
        values = (
            json.dumps(vertices, ensure_ascii=False, allow_nan=False),
            json.dumps(edges, ensure_ascii=False, allow_nan=False),
            json.dumps(result, ensure_ascii=False, allow_nan=False),
        )
        if self.is_postgres:
            import psycopg
            from psycopg.types.json import Jsonb

            try:
                with self._connect_postgres() as connection:
                    row = connection.execute(
                        """
                        INSERT INTO graph_analyses (vertices, edges, result)
                        VALUES (%s, %s, %s)
                        RETURNING id
                        """,
                        tuple(Jsonb(json.loads(value)) for value in values),
                    ).fetchone()
                    return row[0]
            except psycopg.Error as error:
                raise AnalysisStorageError("Falló la escritura en PostgreSQL.") from error

        try:
            with self._sqlite_session() as connection:
                cursor = connection.execute(
                    "INSERT INTO graph_analyses (vertices, edges, result) VALUES (?, ?, ?)",
                    values,
                )
                return cursor.lastrowid
        except sqlite3.Error as error:
            raise AnalysisStorageError("Falló la escritura en SQLite.") from error

    def recent(self, limit=50):
        if self.is_postgres:
            import psycopg

            try:
                with self._connect_postgres() as connection:
                    rows = connection.execute(
                        """
                        SELECT id, created_at, vertices, edges, result
                        FROM graph_analyses
                        ORDER BY created_at DESC, id DESC
                        LIMIT %s
                        """,
                        (limit,),
                    ).fetchall()
            except psycopg.Error as error:
                raise AnalysisStorageError("Falló la consulta en PostgreSQL.") from error
            return [
                {
                    "id": row[0],
                    "created_at": row[1].isoformat(),
                    "vertices": row[2],
                    "edges": row[3],
                    "analysis": row[4],
                }
                for row in rows
            ]

        try:
            with self._sqlite_session() as connection:
                rows = connection.execute(
                    """
                    SELECT id, created_at, vertices, edges, result
                    FROM graph_analyses
                    ORDER BY id DESC
                    LIMIT ?
                    """,
                    (limit,),
                ).fetchall()
        except sqlite3.Error as error:
            raise AnalysisStorageError("Falló la consulta en SQLite.") from error
        return [
            {
                "id": row["id"],
                "created_at": row["created_at"],
                "vertices": json.loads(row["vertices"]),
                "edges": json.loads(row["edges"]),
                "analysis": json.loads(row["result"]),
            }
            for row in rows
        ]
